// Listing copy generation from project metadata.

import 'dart:io';


import '../project.dart';

/// All store-listing fields for one project.
class StoreListing {
  final List<GeneratedFile> files;

  StoreListing(this.files);
}

/// Character limits for the two major stores.
const appStoreLimits = (
  title: 30,
  subtitle: 30,
  keywords: 100,
  description: 4000,
);

const playStoreLimits = (
  title: 30,
  shortDescription: 80,
  fullDescription: 4000,
);

/// Generates the listing from the project's pubspec/package metadata and the
/// first paragraphs of the README.
StoreListing generateListing(ProjectInfo project) {
  final name = _storeSafeName(project.name);
  final tagline = _tagline(project);
  final featureBullets = _featureBullets(project);
  final descriptionBody = _longDescription(project, featureBullets);

  final files = <GeneratedFile>[];

  files.add(GeneratedFile(
    'app_store.md',
    '''
# App Store listing — $name

**Title** (${appStoreLimits.title} chars max)
```
$name
```

**Subtitle** (${appStoreLimits.subtitle} chars max)
```
$tagline
```

**Keywords** (${appStoreLimits.keywords} chars max — comma-separated, no spaces)
```
${_keywords(project)}
```

**Description** (${appStoreLimits.description} chars max)
```
$descriptionBody
```
''',
  ));

  files.add(GeneratedFile(
    'play_store.md',
    '''
# Play Store listing — $name

**Title** (${playStoreLimits.title} chars max)
```
$name
```

**Short description** (${playStoreLimits.shortDescription} chars max)
```
$tagline
```

**Full description** (${playStoreLimits.fullDescription} chars max)
```
$descriptionBody
```
''',
  ));

  files.add(GeneratedFile(
    'README.md',
    '''
# Store listings for $name

Generated by `shipcheck listing` on ${DateTime.now().toIso8601String().substring(0, 10)}.

- `app_store.md` — fields for App Store Connect
- `play_store.md` — fields for Google Play Console

Edit the copy, then paste each fenced block into the corresponding store
field. Keep an eye on the character counts printed with each field.
''',
  ));

  return StoreListing(files);
}

/// Derives a store-safe app display name: underscores removed, capitalized.
String _storeSafeName(String name) {
  final words = name
      .split(RegExp(r'[_\-]'))
      .map((word) => word.isEmpty ? word : word[0].toUpperCase() + word.substring(1));
  return words.join(' ');
}

/// Builds a ≤30-char tagline from the description or a sensible default.
String _tagline(ProjectInfo project) {
  final description = project.description.trim();
  if (description.isEmpty) {
    return 'A ${project.kind.label} app by ${_defaultAuthor()}';
  }
  final firstSentence =
      description.split(RegExp(r'(?<=[.!?])\s')).first.trim();
  final cleaned = firstSentence
      .replaceFirst(RegExp(r'^[Aa]n?\s'), '')
      .replaceFirstMapped(RegExp(r'^[A-Z]'), (m) => m.group(0)!.toLowerCase());
  final tagline = cleaned.length <= 30 ? cleaned : '${cleaned.substring(0, 27)}…';
  return _capitalize(tagline);
}

String _capitalize(String text) =>
    text.isEmpty ? text : text[0].toUpperCase() + text.substring(1);

/// Extracts up to 5 feature bullets from the README's bullet lists.
List<String> _featureBullets(ProjectInfo project) {
  final readme = _readFirstReadme(project.directory);
  final bullets = <String>[];
  for (final line in readme.split('\n')) {
    final match = RegExp(r'^\s*[-*]\s+(.+)$').firstMatch(line);
    if (match != null) {
      final text = match.group(1)!.trim().replaceAll(RegExp(r'[*`]'), '');
      if (text.length > 8 && text.length < 90) {
        bullets.add(text);
      }
    }
    if (bullets.length >= 5) break;
  }
  if (bullets.isEmpty) {
    bullets
      ..add('Built with ${project.kind.label}')
      ..add('Open source — inspect exactly what runs on your device');
  }
  return bullets;
}

/// Composes the long description: hook, features, and closing CTA.
String _longDescription(ProjectInfo project, List<String> bullets) {
  final buffer = StringBuffer();
  buffer.writeln(project.description.trim().isEmpty
      ? '${_storeSafeName(project.name)} is a ${project.kind.label} app.'
      : project.description.trim());
  buffer.writeln();
  buffer.writeln('Why you will like it:');
  for (final bullet in bullets) {
    final text = bullet[0].toUpperCase() + bullet.substring(1);
    buffer.writeln('• $text');
  }
  buffer.writeln();
  buffer.writeln(
      '${_storeSafeName(project.name)} is open source. Feedback and ideas are welcome at the project repository.');
  return buffer.toString().trimRight();
}

/// Keyword set derived from the project name and description words.
String _keywords(ProjectInfo project) {
  final words = <String>{};
  void addWords(String text) {
    for (final word in text.toLowerCase().split(RegExp(r'[^a-z0-9]+'))) {
      if (word.length > 2 && word.length < 15) {
        words.add(word);
      }
    }
  }

  addWords(project.name.replaceAll(RegExp(r'[_\-]'), ' '));
  addWords(project.description);
  final keywords = words.take(10).toList();
  var joined = keywords.join(',');
  if (joined.length > appStoreLimits.keywords) {
    while (joined.length > appStoreLimits.keywords && keywords.length > 3) {
      keywords.removeLast();
      joined = keywords.join(',');
    }
  }
  return joined;
}

String _defaultAuthor() => 'the developer';

String _readFirstReadme(String directory) {
  for (final name in const ['README.md', 'readme.md']) {
    final file = File(_p(directory, name));
    if (file.existsSync()) return file.readAsStringSync();
  }
  return '';
}

// Local p.join to keep imports minimal.
String _p(String a, String b) => '$a${Platform.pathSeparator}$b';
